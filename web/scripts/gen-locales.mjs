// Writes src/i18n/loaders.generated.ts: loaders for the UI locales that are enabled
// (NEXT_PUBLIC_ENABLED_LOCALES, default "en") AND translated. Only those message files are
// bundled; untranslated ones stay in messages/ but out of the build. Runs before dev/build.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const enabled = (process.env.NEXT_PUBLIC_ENABLED_LOCALES || "en").split(",").map((s) => s.trim()).filter(Boolean);
const lines = [];
for (const locale of enabled) {
  if (locale === "en") continue; // English is always bundled (it is the fallback)
  let data = {};
  try {
    data = JSON.parse(readFileSync(join(root, "messages", `${locale}.json`), "utf8"));
  } catch {
    console.warn(`gen-locales: messages/${locale}.json not found, skipping`);
    continue;
  }
  if (!Object.keys(data).some((k) => !k.startsWith("_"))) {
    console.warn(`gen-locales: ${locale} is enabled but untranslated, so it is not bundled (English shows)`);
    continue;
  }
  lines.push(`  ${JSON.stringify(locale)}: () => import("../../messages/${locale}.json"),`);
}
writeFileSync(
  join(root, "src/i18n/loaders.generated.ts"),
  `// Generated by scripts/gen-locales.mjs from NEXT_PUBLIC_ENABLED_LOCALES. Do not edit.
type Loader = () => Promise<{ default: Record<string, unknown> }>;
export const loaders: Record<string, Loader> = {
${lines.join("\n")}
};
`,
);
